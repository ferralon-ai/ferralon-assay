package main

import (
	"encoding/json"
	"fmt"
	"strings"
)

// markdown renders the packet as the page a reviewer reads.
func (p Packet) markdown() string {
	var b strings.Builder
	t := p.Target
	ids := ""
	if a, ok := p.Row["advisory"].([]any); ok {
		parts := make([]string, len(a))
		for i, x := range a {
			parts[i] = fmt.Sprint(x)
		}
		ids = strings.Join(parts, ", ")
	}
	fmt.Fprintf(&b, "# Review packet: %s on %s\n\n", fmt.Sprint(p.Row["package"]), t.Name)
	b.WriteString("Generated by `floorcheck packet`. It decides nothing: read the path, then record `path_review.status` (`real`, `artifact` or `unclear`)\n" +
		"and the row's `adjudicated` conclusion in a pull request that names the reviewer (docs/floor.md, \"Review a row\").\n")
	if len(p.Notes) > 0 {
		b.WriteString("\n## Notes\n\n")
		for _, n := range p.Notes {
			fmt.Fprintf(&b, "- **%s**\n", n)
		}
	}
	fmt.Fprintf(&b, "\n## Row\n\n- Advisories: %s\n- Component instance: `%v`\n- Target: `%s` (%s", ids, p.Row["package"], t.Name, t.Repo)
	if t.Tag != "" {
		fmt.Fprintf(&b, " %s", t.Tag)
	}
	fmt.Fprintf(&b, ") at [`%s`](https://github.com/%s/commit/%s)\n\nThe ledger row, as stored:\n\n", t.UpstreamSHA, t.Repo, t.UpstreamSHA)
	fmt.Fprintf(&b, "```yaml\n%s```\n", p.rowYAML)

	b.WriteString("\n## Call path\n\nOne hop per line, entrypoint first. A target hop links to the pinned commit; a dependency or standard-library hop to its exact version.\n" +
		"`dispatch?` marks a hop the review aid reads as a likely interface dispatch: Assay does not record edge kinds, so read the source.\n\n")
	for _, h := range p.Hops {
		fmt.Fprintf(&b, "%d. `%s` — %s", h.N, h.Symbol, h.Kind)
		if h.LikelyDispatch {
			b.WriteString(" — **dispatch?**")
		}
		if h.Module != "" {
			fmt.Fprintf(&b, " — `%s@%s`", h.Module, h.Version)
		}
		b.WriteString("\n")
		switch {
		case h.Permalink != "":
			fmt.Fprintf(&b, "   - [%s:%d](%s)\n", h.File, h.Line, h.Permalink)
		case h.File != "":
			fmt.Fprintf(&b, "   - `%s:%d` (no line permalink)\n", h.File, h.Line)
		}
		if h.PkgGoDev != "" {
			fmt.Fprintf(&b, "   - [pkg.go.dev](%s)\n", h.PkgGoDev)
		}
		if h.Unresolved != "" {
			fmt.Fprintf(&b, "   - unresolved: %s\n", h.Unresolved)
		}
		if h.Note != "" {
			fmt.Fprintf(&b, "   - note: %s\n", h.Note)
		}
		if h.LinkCheck != "" {
			fmt.Fprintf(&b, "   - link check: %s\n", h.LinkCheck)
		}
	}

	in := p.Inputs
	b.WriteString("\n## Analysis inputs\n\n")
	fmt.Fprintf(&b, "Recorded by: %s.\n\n| Input | Value |\n|---|---|\n", in.RecordedBy)
	row2 := func(k, v string) {
		if v == "" {
			v = "not recorded"
		}
		fmt.Fprintf(&b, "| %s | %s |\n", k, strings.ReplaceAll(v, "|", "\\|"))
	}
	row2("Assay version", in.AssayVersion)
	row2("Assay commit", in.AssayCommit)
	row2("Corpus release", in.CorpusRelease)
	row2("Corpus digest", in.CorpusDigest)
	row2("Corpus policy", in.CorpusPolicy)
	row2("Go toolchain", in.GoToolchain)
	row2("GOOS / GOARCH", in.GOOS+" / "+in.GOARCH)
	row2("cgo", fmt.Sprint(in.CGO))
	row2("Build tags", "["+strings.Join(in.BuildTags, " ")+"]")
	row2("Test scope", in.TestScope)
	row2("Component", in.Component)
	row2("Vulnerable symbol", in.Symbol)
	row2("Symbol confidence", in.SymbolConfidence)
	fmt.Fprintf(&b, "\nScan command (as `floor/scan.sh` runs it):\n\n```sh\n%s\n```\n", in.ScanCommand)

	b.WriteString("\n## Assay's finding\n\n")
	if len(p.AssayFinding) == 0 {
		b.WriteString("Not included: no `report.json` was given. Run the scan below, or pass the nightly pinned scan's report with `-report`.\n")
	}
	for _, raw := range p.AssayFinding {
		var pretty strings.Builder
		var v any
		if json.Unmarshal(raw, &v) == nil {
			if js, err := json.MarshalIndent(v, "", "  "); err == nil {
				pretty.Write(js)
			}
		}
		fmt.Fprintf(&b, "```json\n%s\n```\n\n", pretty.String())
	}

	b.WriteString("\n## govulncheck's view\n\n")
	if len(p.Govulncheck) == 0 {
		b.WriteString("govulncheck reports no finding for this advisory on this component instance (`floor/expect/evidence/`).\n")
	}
	for _, f := range p.Govulncheck {
		js, _ := json.MarshalIndent(f, "", "  ")
		fmt.Fprintf(&b, "```json\n%s\n```\n\n", js)
	}

	b.WriteString("\n## Rerun it\n\nFrom a clean machine with git, go, cosign, gh and jq. Each step is one command; the scan takes about as long as the nightly scan job.\n\n```sh\n")
	b.WriteString(strings.Join(p.Rerun, "\n"))
	b.WriteString("\n```\n")
	return b.String()
}
