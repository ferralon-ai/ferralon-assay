// Command genjdkpackages writes depreach's jdkpackages.go: every package of the JDK's own code, per
// feature release, so the engine can leave out a classpath copy of a class the JVM
// loads from the JDK instead.
//
// Each argument is release:label:dir. dir is searched for the JDK's own classes, read as data and
// never run: for 9 and later every *.jmod (the packages its module-info.class's ModulePackages
// attribute lists, and the directory of every class under classes/), for 8 every JAR under
// jre/lib, the boot and extension class paths (the directory of every class). A release may be
// given several times, for images of different operating systems; its packages are the union. A
// 9+ image without jmods (JEP 493) is read from its lib/modules instead.
//
//	go run ./internal/plugin/javaanalysis/depreach/internal/genjdkpackages -o \
//	    internal/plugin/javaanalysis/depreach/jdkpackages.go \
//	    8:"Temurin 8u462-b08 linux-x64":/path/to/jdk8u462-b08 ...
package main

import (
	"archive/zip"
	"bytes"
	"encoding/binary"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
)

func main() {
	out := flag.String("o", "", "output file")
	flag.Parse()
	if *out == "" || flag.NArg() == 0 {
		fmt.Fprintln(os.Stderr, "usage: genjdkpackages -o out.go release:label:dir ...")
		os.Exit(2)
	}
	src, err := generate(flag.Args())
	if err == nil {
		err = os.WriteFile(*out, src, 0o644)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "genjdkpackages:", err)
		os.Exit(1)
	}
}

func generate(args []string) ([]byte, error) {
	owned := map[string]map[int]bool{} // package -> releases
	labels := map[int][]string{}
	for _, a := range args {
		rel, rest, ok1 := strings.Cut(a, ":")
		label, dir, ok2 := strings.Cut(rest, ":")
		n, err := strconv.Atoi(rel)
		if !ok1 || !ok2 || err != nil || n < 8 {
			return nil, fmt.Errorf("%q: want release:label:dir", a)
		}
		pkgs, err := packages(dir, n)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", dir, err)
		}
		if len(pkgs) == 0 {
			return nil, fmt.Errorf("%s: no JDK classes found", dir)
		}
		for p := range pkgs {
			if owned[p] == nil {
				owned[p] = map[int]bool{}
			}
			owned[p][n] = true
		}
		labels[n] = append(labels[n], label)
	}
	releases := slices.Sorted(func(yield func(int) bool) {
		for r := range labels {
			if !yield(r) {
				return
			}
		}
	})
	if len(releases) > 16 {
		return nil, errors.New("more than 16 releases do not fit a uint16 mask")
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by genjdkpackages; DO NOT EDIT.\n\npackage depreach\n\n")
	b.WriteString("// jdkReleases are the feature releases jdkPackages covers, generated from:\n//\n")
	for _, r := range releases {
		slices.Sort(labels[r])
		for _, l := range labels[r] {
			fmt.Fprintf(&b, "//\t%d: %s\n", r, l)
		}
	}
	b.WriteString("var jdkReleases = [...]int{")
	for i, r := range releases {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(strconv.Itoa(r))
	}
	b.WriteString("}\n\n")
	b.WriteString("// jdkPackages maps each package of a covered JDK's own code (a system module's, or on 8 a boot or\n// extension class path class's) to the releases that have it, bit i\n")
	b.WriteString("// for jdkReleases[i].\n")
	b.WriteString("var jdkPackages = map[string]uint16{\n")
	for _, p := range slices.Sorted(func(yield func(string) bool) {
		for p := range owned {
			if !yield(p) {
				return
			}
		}
	}) {
		var mask uint16
		for i, r := range releases {
			if owned[p][r] {
				mask |= 1 << i
			}
		}
		fmt.Fprintf(&b, "\t%q: 0b%0*b,\n", p, len(releases), mask)
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

// packages returns the packages the JDK image under dir defines a class in. For 9 and later the
// jmods are read when the image has them, and its lib/modules otherwise: a JDK built with JEP 493's
// linkable runtime ships no jmods.
func packages(dir string, release int) (map[string]bool, error) {
	pkgs := map[string]bool{}
	var images []string
	err := filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		slash := filepath.ToSlash(p)
		switch {
		case release >= 9 && strings.HasSuffix(p, ".jmod"):
			return readJmod(p, pkgs)
		case release >= 9 && strings.HasSuffix(slash, "/lib/modules"):
			images = append(images, p)
		case release == 8 && strings.HasSuffix(p, ".jar") &&
			(strings.HasSuffix(path.Dir(slash), "/jre/lib") || strings.HasSuffix(path.Dir(slash), "/jre/lib/ext")):
			return readJar(p, pkgs)
		}
		return nil
	})
	if err != nil || len(pkgs) > 0 {
		return pkgs, err
	}
	for _, p := range images {
		if err := readJimage(p, pkgs); err != nil {
			return nil, fmt.Errorf("%s: %w", p, err)
		}
	}
	return pkgs, nil
}

// readJimage reads a runtime image's lib/modules (jdk.internal.jimage): a header, a redirect and
// an offsets table of tableLength entries each, the location attributes, the strings, then the
// resources. Each location names a resource /module/parent/base.extension; a class's parent is its
// package. Each module's module-info.class is read for its ModulePackages too.
func readJimage(p string, pkgs map[string]bool) error {
	data, err := os.ReadFile(p)
	if err != nil {
		return err
	}
	if len(data) < 28 {
		return errors.New("short jimage")
	}
	var bo binary.ByteOrder = binary.LittleEndian
	if bo.Uint32(data) != 0xCAFEDADA {
		bo = binary.BigEndian
		if bo.Uint32(data) != 0xCAFEDADA {
			return errors.New("not a jimage")
		}
	}
	u4 := func(off int) int { return int(bo.Uint32(data[off:])) }
	tableLength, locationsSize, stringsSize := u4(16), u4(20), u4(24)
	offsets := 28 + 4*tableLength
	locations := offsets + 4*tableLength
	strs := locations + locationsSize
	index := strs + stringsSize
	if index > len(data) {
		return errors.New("jimage index past the end")
	}
	str := func(off int) (string, error) {
		if off < 0 || strs+off >= index {
			return "", errors.New("string offset out of range")
		}
		b := data[strs+off : index]
		if i := bytes.IndexByte(b, 0); i >= 0 {
			return string(b[:i]), nil
		}
		return "", errors.New("unterminated string")
	}
	const (
		attrModule = 1 + iota
		attrParent
		attrBase
		attrExtension
		attrOffset
		attrCompressed
		attrUncompressed
	)
	infos := 0
	for i := 0; i < tableLength; i++ {
		at := locations + u4(offsets+4*i)
		var attr [8]int
		for {
			if at >= strs {
				return errors.New("location past the attributes")
			}
			b := data[at]
			kind, n := int(b>>3), int(b&7)+1
			if kind == 0 {
				break
			}
			if kind > attrUncompressed || at+1+n > strs {
				return fmt.Errorf("bad location attribute %#x", b)
			}
			v := 0
			for _, c := range data[at+1 : at+1+n] {
				v = v<<8 | int(c)
			}
			attr[kind] = v
			at += 1 + n
		}
		var name [5]string
		for k := attrModule; k <= attrExtension; k++ {
			if name[k], err = str(attr[k]); err != nil {
				return err
			}
		}
		if name[attrExtension] != "class" || name[attrModule] == "" {
			continue
		}
		if name[attrParent] != "" {
			pkgs[name[attrParent]] = true
			continue
		}
		if name[attrBase] != "module-info" {
			continue
		}
		if attr[attrCompressed] != 0 {
			return fmt.Errorf("%s: compressed module-info.class", name[attrModule])
		}
		start, end := index+attr[attrOffset], index+attr[attrOffset]+attr[attrUncompressed]
		if end > len(data) {
			return fmt.Errorf("%s: module-info.class past the end", name[attrModule])
		}
		listed, err := modulePackages(data[start:end])
		if err != nil {
			return fmt.Errorf("%s: %w", name[attrModule], err)
		}
		for _, q := range listed {
			pkgs[q] = true
		}
		infos++
	}
	if infos == 0 {
		return errors.New("no module-info.class")
	}
	return nil
}

func readJar(p string, pkgs map[string]bool) error {
	z, err := zip.OpenReader(p)
	if err != nil {
		return err
	}
	defer z.Close()
	for _, f := range z.File {
		addClassDir(f.Name, pkgs)
	}
	return nil
}

// readJmod reads a jmod: a 4-byte "JM" header followed by a zip.
func readJmod(p string, pkgs map[string]bool) error {
	data, err := os.ReadFile(p)
	if err != nil {
		return err
	}
	if len(data) < 4 || string(data[:2]) != "JM" {
		return errors.New("not a jmod")
	}
	z, err := zip.NewReader(bytes.NewReader(data[4:]), int64(len(data)-4))
	if err != nil {
		return err
	}
	found := false
	for _, f := range z.File {
		name, ok := strings.CutPrefix(f.Name, "classes/")
		if !ok {
			continue
		}
		if name == "module-info.class" {
			r, err := f.Open()
			if err != nil {
				return err
			}
			mi, err := io.ReadAll(r)
			r.Close()
			if err != nil {
				return err
			}
			listed, err := modulePackages(mi)
			if err != nil {
				return fmt.Errorf("%s: %w", p, err)
			}
			for _, q := range listed {
				pkgs[q] = true
			}
			found = true
			continue
		}
		addClassDir(name, pkgs)
	}
	if !found {
		return fmt.Errorf("%s: no module-info.class", p)
	}
	return nil
}

func addClassDir(name string, pkgs map[string]bool) {
	if !strings.HasSuffix(name, ".class") || strings.HasPrefix(name, "META-INF/") {
		return
	}
	if i := strings.LastIndexByte(name, '/'); i > 0 {
		pkgs[name[:i]] = true
	}
}

// modulePackages returns the packages a module-info.class's ModulePackages attribute lists.
func modulePackages(c []byte) ([]string, error) {
	r := &reader{b: c}
	if r.u4() != 0xCAFEBABE {
		return nil, errors.New("bad magic")
	}
	r.u2()
	r.u2()
	n := int(r.u2())
	utf8 := make(map[int]string)
	pkgName := make(map[int]int)
	for i := 1; i < n && r.err == nil; i++ {
		switch tag := r.u1(); tag {
		case 1:
			utf8[i] = string(r.bytes(int(r.u2())))
		case 3, 4, 9, 10, 11, 12, 17, 18:
			r.bytes(4)
		case 5, 6:
			r.bytes(8)
			i++
		case 7, 8, 16, 19:
			r.u2()
		case 20:
			pkgName[i] = int(r.u2())
		case 15:
			r.bytes(3)
		default:
			return nil, fmt.Errorf("constant pool tag %d", tag)
		}
	}
	r.bytes(6) // access_flags, this_class, super_class
	for _, members := range []bool{false, true, true} {
		if !members {
			r.bytes(2 * int(r.u2())) // interfaces
			continue
		}
		for k := int(r.u2()); k > 0 && r.err == nil; k-- {
			r.bytes(6)
			for a := int(r.u2()); a > 0 && r.err == nil; a-- {
				r.u2()
				r.bytes(int(r.u4()))
			}
		}
	}
	var out []string
	for a := int(r.u2()); a > 0 && r.err == nil; a-- {
		name := utf8[int(r.u2())]
		body := r.bytes(int(r.u4()))
		if name != "ModulePackages" || r.err != nil {
			continue
		}
		br := &reader{b: body}
		for k := int(br.u2()); k > 0 && br.err == nil; k-- {
			out = append(out, utf8[pkgName[int(br.u2())]])
		}
		if br.err != nil {
			return nil, br.err
		}
	}
	if r.err != nil {
		return nil, r.err
	}
	return out, nil // an aggregator such as java.se has no packages and no attribute
}

type reader struct {
	b   []byte
	err error
}

func (r *reader) bytes(n int) []byte {
	if r.err != nil || n < 0 || n > len(r.b) {
		r.err = io.ErrUnexpectedEOF
		return nil
	}
	v := r.b[:n]
	r.b = r.b[n:]
	return v
}

func (r *reader) u1() byte {
	if v := r.bytes(1); v != nil {
		return v[0]
	}
	return 0
}

func (r *reader) u2() uint16 {
	if v := r.bytes(2); v != nil {
		return binary.BigEndian.Uint16(v)
	}
	return 0
}

func (r *reader) u4() uint32 {
	if v := r.bytes(4); v != nil {
		return binary.BigEndian.Uint32(v)
	}
	return 0
}
