func TestResolveVersions_NoLockfileDegradesToNoManifest(t *testing.T) {
	dir := writeLockTree(t, map[string]string{"package.json": packageJSONNoLock})
	res := resolveJS(t, dir, "cookie") // resolveJS t.Fatals on a hard error

	if res.Partiality.Complete {
		t.Fatal("a no-lockfile result must be declared-partial, not Complete — it must be distinguishable from a clean scan")
	}
	if !hasReason(res.Partiality, plugin.PartialReasonNoManifest) {
		t.Fatalf("Reasons = %v, want %q", res.Partiality.Reasons, plugin.PartialReasonNoManifest)
	}
}

// The soundness shape: the requested coordinate is PRESENT-but-UNRESOLVED, never absent.
// Found=false here would let the disqualification predicate read "no dependency" and
// fabricate a not-affected.
func TestResolveVersions_NoLockfileSeedsUnresolvedMatch(t *testing.T) {
	dir := writeLockTree(t, map[string]string{"package.json": packageJSONNoLock})
	res := resolveJS(t, dir, "cookie")

	if !res.Found {
		t.Fatalf("declared coordinate must be Found (present-but-unresolved); all=%+v", res.All)
	}
	if res.Match.Resolved {
		t.Fatalf("declared coordinate must be UNRESOLVED (no version source); match=%+v", res.Match)
	}
	if res.Match.Version != "" {
		t.Fatalf("Version = %q, want empty — the declared range must never be reported as an installed version", res.Match.Version)
	}
	if res.Match.Coordinate != "cookie" {
		t.Fatalf("Coordinate = %q, want %q", res.Match.Coordinate, "cookie")
	}
}

func TestResolveVersions_NoLockfileSeedsAllDeclaredFields(t *testing.T) {
	dir := writeLockTree(t, map[string]string{"package.json": packageJSONNoLock})
	res := resolveJS(t, dir, "")

	got := make(map[string]bool, len(res.All))
	for _, d := range res.All {
		if d.Resolved {
			t.Fatalf("seeded dependency %q must be UNRESOLVED; got %+v", d.Coordinate, d)
		}
		got[d.Coordinate] = true
	}
	for _, want := range []string{"cookie", "qs", "mocha", "fsevents", "react"} {
		if !got[want] {
			t.Fatalf("declared dependency %q missing from All=%v", want, got)
		}
	}
}

