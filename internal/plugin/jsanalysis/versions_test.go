// writeLockTree writes files (path→content, relative to a fresh temp dir) and returns the
// dir. A trivial .js file is always added so the tree is a recognizable JS source tree
// (loadProgram is not exercised here, but it keeps the fixtures realistic).
func writeLockTree(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	files["src/index.js"] = "'use strict';\nfunction main() {}\n"
	for rel, content := range files {
		full := filepath.Join(dir, rel)
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

func resolveJS(t *testing.T, dir, coord string) plugin.DependencyVersionResult {
	t.Helper()
	res, err := ResolveDependencyVersions(context.Background(), plugin.ResolveVersionsRequest{BuildDir: dir, Coordinate: coord})
	if err != nil {
		t.Fatalf("ResolveDependencyVersions: %v", err)
	}
	return res
}

func mustMatch(t *testing.T, res plugin.DependencyVersionResult, wantVer string) {
	t.Helper()
	if !res.Found {
		t.Fatalf("coordinate not found; all=%+v", res.All)
	}
	if !res.Match.Resolved {
		t.Fatalf("match UNRESOLVED, want resolved %q; match=%+v", wantVer, res.Match)
	}
	if res.Match.Version != wantVer {
		t.Fatalf("version = %q, want %q", res.Match.Version, wantVer)
	}
}

// --- package-lock.json -------------------------------------------------------

const packageLockV3 = `{
  "name": "app",
  "lockfileVersion": 3,
  "requires": true,
  "packages": {
    "": { "name": "app", "version": "1.0.0" },
    "node_modules/left-pad": { "version": "1.3.0" },
    "node_modules/express": { "version": "4.18.2" },
    "node_modules/express/node_modules/cookie": { "version": "0.5.0" }
  }
}`

const packageLockV2 = `{
  "name": "app",
  "lockfileVersion": 2,
  "packages": {
    "": { "name": "app", "version": "1.0.0" },
    "node_modules/left-pad": { "version": "1.4.0" }
  },
  "dependencies": {
    "left-pad": { "version": "1.4.0" }
  }
}`

const packageLockV1 = `{
  "name": "app",
  "lockfileVersion": 1,
  "dependencies": {
    "left-pad": { "version": "1.2.0" },
    "express": {
      "version": "4.17.1",
      "dependencies": {
        "cookie": { "version": "0.4.0" }
      }
    }
  }
}`

func TestPackageLock_V3_PackagesMap(t *testing.T) {
	dir := writeLockTree(t, map[string]string{"package-lock.json": packageLockV3})
	mustMatch(t, resolveJS(t, dir, "left-pad"), "1.3.0")
	mustMatch(t, resolveJS(t, dir, "express"), "4.18.2")
	// nested transitive (the express-scoped cookie) is also resolved
	mustMatch(t, resolveJS(t, dir, "cookie"), "0.5.0")
}

func TestPackageLock_V2_PreferPackagesMap(t *testing.T) {
	dir := writeLockTree(t, map[string]string{"package-lock.json": packageLockV2})
	mustMatch(t, resolveJS(t, dir, "left-pad"), "1.4.0")
}

func TestPackageLock_V1_DependenciesMap(t *testing.T) {
	dir := writeLockTree(t, map[string]string{"package-lock.json": packageLockV1})
	mustMatch(t, resolveJS(t, dir, "left-pad"), "1.2.0")
	mustMatch(t, resolveJS(t, dir, "express"), "4.17.1")
	mustMatch(t, resolveJS(t, dir, "cookie"), "0.4.0") // nested v1 transitive
}

func TestPackageLock_RootPackageNotADependency(t *testing.T) {
	dir := writeLockTree(t, map[string]string{"package-lock.json": packageLockV3})
	res := resolveJS(t, dir, "app")
	if res.Found {
		t.Fatalf("root package 'app' must not be reported as a dependency; got %+v", res.Match)
	}
}

func TestPackageLock_Unparseable_IsPartial(t *testing.T) {
	dir := writeLockTree(t, map[string]string{"package-lock.json": "{ not valid json"})
	res := resolveJS(t, dir, "left-pad")
	if res.Partiality.Complete {
		t.Fatal("unparseable lockfile must degrade to declared-partial")
	}
	if res.Found {
		t.Fatalf("nothing should resolve from an unparseable lockfile; got %+v", res.Match)
	}
}

// --- yarn.lock ---------------------------------------------------------------

const yarnClassic = `# THIS IS AN AUTOGENERATED FILE.
# yarn lockfile v1


left-pad@^1.3.0:
  version "1.3.0"
  resolved "https://registry.yarnpkg.com/left-pad/-/left-pad-1.3.0.tgz"
  integrity sha512-xxx

"@scope/pkg@^2.0.0":
  version "2.1.0"
  resolved "https://registry.yarnpkg.com/@scope/pkg/-/pkg-2.1.0.tgz"

express@^4.0.0, express@^4.18.0:
  version "4.18.2"
`

const yarnBerry = `# This file is generated by running "yarn install" inside your project.
# Manual changes might be lost - proceed with caution!

__metadata:
  version: 6
  cacheKey: 8

"left-pad@npm:^1.3.0":
  version: 1.3.0
  resolution: "left-pad@npm:1.3.0"
  checksum: abc

"@scope/pkg@npm:^2.0.0":
  version: 2.1.0
  resolution: "@scope/pkg@npm:2.1.0"
`

func TestYarnLock_Classic(t *testing.T) {
	dir := writeLockTree(t, map[string]string{"yarn.lock": yarnClassic})
	mustMatch(t, resolveJS(t, dir, "left-pad"), "1.3.0")
	mustMatch(t, resolveJS(t, dir, "@scope/pkg"), "2.1.0")
	mustMatch(t, resolveJS(t, dir, "express"), "4.18.2") // multi-descriptor header
}

func TestYarnLock_Berry(t *testing.T) {
	dir := writeLockTree(t, map[string]string{"yarn.lock": yarnBerry})
	mustMatch(t, resolveJS(t, dir, "left-pad"), "1.3.0")
	mustMatch(t, resolveJS(t, dir, "@scope/pkg"), "2.1.0")
	// __metadata is not a package entry
	if res := resolveJS(t, dir, "__metadata"); res.Found {
		t.Fatalf("__metadata must not be a resolved dependency; got %+v", res.Match)
	}
}

func TestYarnLock_NoVersionLine_IsUnresolved(t *testing.T) {
	const noVer = `broken@^1.0.0:
  resolved "https://example.com/broken.tgz"
`
	dir := writeLockTree(t, map[string]string{"yarn.lock": noVer})
	res := resolveJS(t, dir, "broken")
	if !res.Found {
		t.Fatal("the entry should be FOUND (declared) even without a version")
	}
	if res.Match.Resolved {
		t.Fatalf("a yarn entry with no version line must be UNRESOLVED; got %+v", res.Match)
	}
}

