// writeLockTree writes files (path→content, relative to a fresh temp dir) and returns the
// dir. A trivial .js file is always added so the tree is a recognizable JS source tree
// (loadProgram is not exercised here, but it keeps the fixtures realistic).
func writeLockTree(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	files["src/index.js"] = "'use strict';\nfunction main() {}\n"
	for rel, content := range files {
		full := filepath.Join(dir, rel)
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

func resolveJS(t *testing.T, dir, coord string) plugin.DependencyVersionResult {
	t.Helper()
	res, err := ResolveDependencyVersions(context.Background(), plugin.ResolveVersionsRequest{BuildDir: dir, Coordinate: coord})
	if err != nil {
		t.Fatalf("ResolveDependencyVersions: %v", err)
	}
	return res
}

func mustMatch(t *testing.T, res plugin.DependencyVersionResult, wantVer string) {
	t.Helper()
	if !res.Found {
		t.Fatalf("coordinate not found; all=%+v", res.All)
	}
	if !res.Match.Resolved {
		t.Fatalf("match UNRESOLVED, want resolved %q; match=%+v", wantVer, res.Match)
	}
	if res.Match.Version != wantVer {
		t.Fatalf("version = %q, want %q", res.Match.Version, wantVer)
	}
}

