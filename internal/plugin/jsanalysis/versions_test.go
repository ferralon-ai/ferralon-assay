func TestResolveVersions_MissingBuildDirIsHardError(t *testing.T) {
	_, err := ResolveDependencyVersions(context.Background(), plugin.ResolveVersionsRequest{
		BuildDir:   filepath.Join(t.TempDir(), "nope"),
		Coordinate: "left-pad",
	})
	if err == nil {
		t.Fatal("a missing build dir must be a hard error")
	}
}

func TestResolveVersions_CoordinateNotDeclaredNotFound(t *testing.T) {
	dir := writeLockTree(t, map[string]string{"package-lock.json": packageLockV3})
	res := resolveJS(t, dir, "nonexistent-pkg")
	if res.Found {
		t.Fatalf("an undeclared coordinate must be Found=false; got %+v", res.Match)
	}
	if !res.Partiality.Complete {
		t.Fatal("a clean parse with a missing coordinate is still Complete (the absence is known)")
	}
}
