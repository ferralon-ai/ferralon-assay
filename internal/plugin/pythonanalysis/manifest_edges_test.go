// poetry.lock [package.dependencies] (and the optional deps [package.extras] gates) are real
// parent edges; a dependency whose marker evaluates false contributes no edge.
func TestPoetryLockEdges(t *testing.T) {
	const lock = `[[package]]
name = "flask"
version = "3.0.0"
optional = false

[package.dependencies]
Jinja2 = ">=3.1.2"
click = ">=8.1.3"
colorama = { version = "*", markers = "platform_system == \"Windows\"" }
importlib-metadata = [
    { version = ">=3.6", markers = "python_version < \"3.10\"" },
    { version = ">=4.0", markers = "python_version >= \"3.12\"" },
]

[package.extras]
async = ["asgiref (>=3.2)"]

[[package]]
name = "jinja2"
version = "3.1.4"

[package.dependencies]
MarkupSafe = ">=2.0"

[[package]]
name = "markupsafe"
version = "2.1.5"

[[package]]
name = "click"
version = "8.1.7"

[[package]]
name = "colorama"
version = "0.4.6"

[[package]]
name = "importlib-metadata"
version = "8.0.0"

[[package]]
name = "asgiref"
version = "3.8.1"
optional = true
`
	linux := map[string]string{"platform_system": "Linux", "python_version": "3.11"}
	tests := []struct {
		name        string
		env         map[string]string
		pkg         string
		wantRel     string
		wantParents []string
	}{
		{"root is direct", linux, "flask", "direct", nil},
		{"plain string edge, case-normalized parent", linux, "jinja2", "transitive", []string{"flask"}},
		{"second-level edge", linux, "markupsafe", "transitive", []string{"jinja2"}},
		{"marker-false edge dropped", linux, "colorama", "direct", nil},
		{"marker-true edge kept", map[string]string{"platform_system": "Windows", "python_version": "3.11"}, "colorama", "transitive", []string{"flask"}},
		{"array form: no element active", linux, "importlib-metadata", "direct", nil},
		{"array form: one element active", map[string]string{"platform_system": "Linux", "python_version": "3.9"}, "importlib-metadata", "transitive", []string{"flask"}},
		{"unbound marker keeps edge", nil, "colorama", "transitive", []string{"flask"}},
		{"extras-gated package not depended on is a root", linux, "asgiref", "direct", nil},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			reqs, err := parsePoetryLockSelected([]byte(lock), tt.env, nil)
			if err != nil {
				t.Fatalf("parse: %v", err)
			}
			r, ok := byNamePyReq(reqs)[tt.pkg]
			if !ok {
				t.Fatalf("%s missing from %+v", tt.pkg, reqs)
			}
			if r.Source != "poetry.lock" || !r.Resolved {
				t.Fatalf("%s: source=%q resolved=%v", tt.pkg, r.Source, r.Resolved)
			}
			if got := relKindName(r.Relationship); got != tt.wantRel || !equalStrings(r.Parents, tt.wantParents) {
				t.Fatalf("%s: rel=%s parents=%v, want rel=%s parents=%v", tt.pkg, got, r.Parents, tt.wantRel, tt.wantParents)
			}
		})
	}
}

func TestPoetryLockMalformed(t *testing.T) {
	if _, err := parsePoetryLockSelected([]byte("[[package]]\nname = \"x\"\n[package.dependencies\n"), nil, nil); err == nil {
		t.Fatal("malformed poetry.lock parsed without error")
	}
}

// pip-compile "# via" annotations become parent edges in all three shapes; an input file or
// the project itself marks a requirement direct; a constraint file proves nothing; a parent the
// file does not list yields no edge; an unannotated file stays unexpressed.
func TestPipCompileViaEdges(t *testing.T) {
	const compiled = `#
# This file is autogenerated by pip-compile with Python 3.11
#
aiohttp==3.9.1
    # via
    #   -r requirements.in
    #   langchain
aiosignal==1.3.1
    # via aiohttp
attrs==23.1.0
    # via
    #   aiohttp
    #   jsonschema
frozenlist==1.4.0
    # via aiohttp, aiosignal
langchain==0.1.0
    # via my-app (pyproject.toml)
six==1.16.0               # via python-dateutil, langchain
urllib3==2.0.7
    # via
    #   -c constraints.txt
    #   ghost-package
yarl==1.9.4
    # via -c constraints.txt
colorama==0.4.6 ; platform_system == "Windows"
    # via click
click==8.1.7
    # via -r requirements.in
`
	tests := []struct {
		name        string
		data        string
		pkg         string
		wantRel     string
		wantParents []string
	}{
		{"multi-line block with input file and parent", compiled, "aiohttp", "direct", []string{"langchain"}},
		{"single-line via", compiled, "aiosignal", "transitive", []string{"aiohttp"}},
		{"multi-line parents only", compiled, "attrs", "transitive", []string{"aiohttp"}},
		{"comma-separated via", compiled, "frozenlist", "transitive", []string{"aiohttp", "aiosignal"}},
		{"project itself is direct", compiled, "langchain", "direct", nil},
		{"inline via, unlisted parent dropped", compiled, "six", "transitive", []string{"langchain"}},
		{"constraint plus unlisted parent stays unexpressed", compiled, "urllib3", "unexpressed", nil},
		{"constraint only stays unexpressed", compiled, "yarl", "unexpressed", nil},
		{"input file only is direct", compiled, "click", "direct", nil},
		{"unannotated requirements stay unexpressed", "flask==3.0.0\njinja2==3.1.4\n", "jinja2", "unexpressed", nil},
	}
	env := map[string]string{"platform_system": "Linux", "python_version": "3.11"}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			reqs := resolveRequirements([]byte(tt.data), env, nil)
			applyViaEdges(reqs, pipCompileVia([]byte(tt.data)))
			r, ok := byNamePyReq(reqs)[tt.pkg]
			if !ok {
				t.Fatalf("%s missing", tt.pkg)
			}
			if got := relKindName(r.Relationship); got != tt.wantRel || !equalStrings(r.Parents, tt.wantParents) {
				t.Fatalf("%s: rel=%s parents=%v, want rel=%s parents=%v", tt.pkg, got, r.Parents, tt.wantRel, tt.wantParents)
			}
		})
	}
	// A marker-false parent contributes no edge.
	reqs := resolveRequirements([]byte(compiled), env, nil)
	applyViaEdges(reqs, pipCompileVia([]byte(compiled)))
	for _, r := range reqs {
		for _, p := range r.Parents {
			if p == "colorama" {
				t.Fatalf("%s has marker-false parent colorama", r.Name)
			}
		}
	}
}

// The new edges surface in the assembled inventory as DependencyEdges between real node IDs,
// and a pip-compile requirement with no annotation keeps relationship_unexpressed.
func TestInventoryManifestEdges(t *testing.T) {
	tests := []struct {
		name       string
		files      map[string]string
		wantEdge   [2]string // parent, child node IDs
		directPURL string
		transPURL  string
	}{
		{
			name: "poetry.lock",
			files: map[string]string{"poetry.lock": `[[package]]
name = "flask"
version = "3.0.0"

[package.dependencies]
jinja2 = ">=3.1.2"

[[package]]
name = "jinja2"
version = "3.1.4"
`},
			wantEdge:   [2]string{"poetry.lock#flask", "poetry.lock#jinja2"},
			directPURL: "pkg:pypi/flask@3.0.0",
			transPURL:  "pkg:pypi/jinja2@3.1.4",
		},
		{
			name: "pip-compile via",
			files: map[string]string{"requirements.txt": `flask==3.0.0
    # via -r requirements.in
jinja2==3.1.4
    # via flask
`},
			wantEdge:   [2]string{"requirements.txt#flask", "requirements.txt#jinja2"},
			directPURL: "pkg:pypi/flask@3.0.0",
			transPURL:  "pkg:pypi/jinja2@3.1.4",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			inv, err := ResolveInventory(context.Background(), plugin.ResolveInventoryRequest{BuildDir: writeTree(t, tt.files)})
			if err != nil {
				t.Fatalf("ResolveInventory: %v", err)
			}
			ids := map[string]bool{}
			for _, n := range inv.Nodes {
				ids[n.ID] = true
			}
			found := false
			for _, e := range inv.Edges {
				if !ids[e.Parent] || !ids[e.Child] {
					t.Errorf("edge %+v references a non-existent node", e)
				}
				if e.Parent == tt.wantEdge[0] && e.Child == tt.wantEdge[1] {
					found = true
				}
			}
			if !found {
				t.Fatalf("no edge %v; edges=%+v nodes=%v", tt.wantEdge, inv.Edges, ids)
			}
			d, ok := nodeByPURL(inv, tt.directPURL)
			if !ok || !d.Direct || hasReason(d.Partiality, plugin.PartialReasonRelationshipUnexpressed) {
				t.Fatalf("%s: want direct, classified; got %+v ok=%v", tt.directPURL, d, ok)
			}
			c, ok := nodeByPURL(inv, tt.transPURL)
			if !ok || c.Direct || hasReason(c.Partiality, plugin.PartialReasonRelationshipUnexpressed) {
				t.Fatalf("%s: want transitive, classified; got %+v ok=%v", tt.transPURL, c, ok)
			}
		})
	}
}
